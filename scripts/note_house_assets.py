"""Extract the licensed Bravura grand-staff brace without redrawing it."""
from pathlib import Path
import json
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.boundsPen import BoundsPen

ROOT = next(p for p in Path(__file__).resolve().parents if (p / ".git").exists())
font = TTFont(ROOT / "assets/BravuraText.woff2")
glyphs = font.getGlyphSet()
glyph = glyphs[font.getBestCmap()[0xE000]]
path = SVGPathPen(glyphs)
glyph.draw(path)
bounds = BoundsPen(glyphs)
glyph.draw(bounds)
data = {"path": path.getCommands(), "bounds": bounds.bounds}
(ROOT / "src/note_house_glyphs.mjs").write_text(
    "// Bravura SMuFL E000 brace, SIL OFL; generated by scripts/note_house_assets.py.\n"
    + "export const braceGlyph = " + json.dumps(data) + ";\n"
)
